//! Stock Whisper's language tokens: the ONE owner of "which language can
//! Whisper be told to decode, and by what name".
//!
//! # Why a token, not a name or an ISO code
//!
//! Whisper's decoder is told its language by a token from its own vocabulary:
//! `en`, `el`, `yue`, `haw`, and `jw` for Javanese. That set is a fact about
//! the model. Most ISO 639-1 codes have no token, and one token (`jw`) is no
//! ISO code at all. Before this module the control plane guessed membership
//! from ISO 639-1 while the worker handed Whisper a pycountry language NAME,
//! and the two disagreed in both directions: languages with no token were
//! admitted and then failed on every file, and six languages Whisper does
//! support (Greek among them) failed because their registry names are not
//! Whisper's. Now the control plane admits exactly the languages that have a
//! token and sends the worker the token itself.
//!
//! # Where the data comes from
//!
//! [`table`] is generated by `scripts/generate_whisper_language_table.py` from
//! the token table of the Whisper decoder the worker runs (transformers'
//! `LANGUAGES`), each token paired with its ISO 639-3 code through pycountry.
//! [`table::SOURCE`] carries the exact provenance into the binary.
//!
//! whisper.cpp (`whisper_rs`) keeps its own narrower table in
//! `whisper_native`; this module is the transformers decoder's.

mod table;

pub use table::SOURCE;

use crate::domain::LanguageCode3;

/// A language token stock Whisper's decoder accepts.
///
/// The field is private and the only constructors read the generated table,
/// so a value is proof that Whisper has this token. No caller can mint one
/// from a guess.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct WhisperLanguageToken(&'static str);

impl WhisperLanguageToken {
    /// The token Whisper decodes `language` with, or `None` when it has none.
    #[must_use]
    pub fn for_language(language: &LanguageCode3) -> Option<Self> {
        let code: &str = language.as_ref();
        table::ISO_639_3_TO_WHISPER
            .binary_search_by(|(iso3, _)| (*iso3).cmp(code))
            .ok()
            .map(|index| Self(table::ISO_639_3_TO_WHISPER[index].1))
    }

    /// The token named by its own spelling, as the worker boundary reads it
    /// back. `None` for anything that is not one of Whisper's tokens.
    #[must_use]
    pub fn from_token(token: &str) -> Option<Self> {
        table::ISO_639_3_TO_WHISPER
            .iter()
            .find(|(_, known)| *known == token)
            .map(|(_, known)| Self(known))
    }

    /// The token's spelling, as Whisper's decoder takes it.
    #[must_use]
    pub const fn as_str(self) -> &'static str {
        self.0
    }

    /// Every distinct token, sorted: the closed set the wire schema names.
    fn all() -> std::collections::BTreeSet<&'static str> {
        table::ISO_639_3_TO_WHISPER
            .iter()
            .map(|(_, token)| *token)
            .collect()
    }
}

impl std::fmt::Display for WhisperLanguageToken {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(self.0)
    }
}

impl serde::Serialize for WhisperLanguageToken {
    fn serialize<S: serde::Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        serializer.serialize_str(self.0)
    }
}

impl<'de> serde::Deserialize<'de> for WhisperLanguageToken {
    fn deserialize<D: serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        let spelling = String::deserialize(deserializer)?;
        Self::from_token(&spelling).ok_or_else(|| {
            serde::de::Error::custom(format!(
                "{spelling:?} is not a stock Whisper language token"
            ))
        })
    }
}

// The schema names the closed set itself, so the worker's mirror can be
// checked against exactly the tokens this table holds.
impl schemars::JsonSchema for WhisperLanguageToken {
    fn schema_name() -> std::borrow::Cow<'static, str> {
        "WhisperLanguageToken".into()
    }

    fn json_schema(_generator: &mut schemars::SchemaGenerator) -> schemars::Schema {
        let tokens: Vec<&str> = Self::all().into_iter().collect();
        schemars::json_schema!({ "type": "string", "enum": tokens })
    }
}

#[cfg(test)]
#[allow(clippy::expect_used)] // fixture codes are known-valid literals
mod tests {
    use super::*;

    fn code(raw: &str) -> LanguageCode3 {
        LanguageCode3::try_new(raw).expect("valid ISO 639-3 fixture")
    }

    #[test]
    fn the_generated_table_is_sorted_and_has_no_duplicates() {
        assert!(
            table::ISO_639_3_TO_WHISPER
                .windows(2)
                .all(|pair| pair[0].0 < pair[1].0),
            "binary search needs strictly sorted ISO codes"
        );
    }

    /// The registry's pairing, the three-letter tokens, the one token that is
    /// no ISO code, and the alias.
    #[test]
    fn languages_map_to_the_token_whisper_decodes_them_with() {
        for (iso3, token) in [
            ("eng", "en"),
            ("ell", "el"),
            ("msa", "ms"),
            ("swa", "sw"),
            ("yue", "yue"),
            ("haw", "haw"),
            ("jav", "jw"),
            ("zho", "zh"),
            ("cmn", "zh"),
        ] {
            assert_eq!(
                WhisperLanguageToken::for_language(&code(iso3)).map(WhisperLanguageToken::as_str),
                Some(token),
                "{iso3}"
            );
        }
    }

    /// A two-letter ISO code is not a Whisper token: Zulu has one and Whisper
    /// has no token for it; Taiwanese has neither.
    #[test]
    fn languages_whisper_has_no_token_for_are_absent() {
        for iso3 in ["zul", "xho", "que", "nan"] {
            assert_eq!(
                WhisperLanguageToken::for_language(&code(iso3)),
                None,
                "{iso3}"
            );
        }
    }

    #[test]
    fn the_wire_form_is_the_token_and_only_tokens_parse() {
        let greek = WhisperLanguageToken::for_language(&code("ell")).expect("Greek");
        assert_eq!(
            serde_json::to_string(&greek).expect("serializes"),
            r#""el""#
        );
        assert_eq!(
            serde_json::from_str::<WhisperLanguageToken>(r#""jw""#).expect("Javanese"),
            WhisperLanguageToken::for_language(&code("jav")).expect("Javanese")
        );
        for refused in [r#""jv""#, r#""eng""#, r#""greek""#, r#""""#] {
            assert!(
                serde_json::from_str::<WhisperLanguageToken>(refused).is_err(),
                "{refused}"
            );
        }
    }

    #[test]
    fn the_table_records_where_it_came_from() {
        // The token set itself is checked against transformers by the
        // worker's IPC conformance test, which fails until this table is
        // regenerated after an upgrade.
        assert!(SOURCE.contains("transformers"), "{SOURCE}");
    }
}
