    #[test]
    fn derive_verdicts_requires_every_entry_to_agree_and_nothing_to_derive() {
        let raw = derive_verdicts(
            vec![
                entry("whoops", "co", None),
                // `whoop` is a communicator, a noun and a verb: no verdict.
                entry("whoop", "co", None),
                entry("whoop", "n", None),
                entry("whoop", "v", None),
                // A plural entry carries the bare stem as lemma.
                entry("children", "n", Some("child&PL")),
                // Two noun entries that disagree on number: no verdict.
                entry("fish", "n", None),
                entry("fish", "n", Some("fish&PL")),
                // Compounds never reach Stanza in this shape.
                entry("doggy+dog", "n", None),
                // A proper-noun subcategory is not the plain noun category.
                entry("miffy", "n:prop", None),
                // Noun-only entries MOR could also derive as something else
                // get no verdict: `sticky` is `stick` + adjectival `-y`,
                // `doggy` is `dog` + `-y`, `building` is `build` + `-ing`,
                // `lives` is `live` + `-s`; `babies` derives only from a noun
                // and is kept.
                entry("sticky", "n", None),
                entry("stick", "v", None),
                entry("doggy", "n", Some("dog-DIM")),
                entry("dog", "n", None),
                entry("building", "n", None),
                entry("build", "v", None),
                entry("lives", "n", Some("life&PL")),
                entry("live", "v", None),
                entry("babies", "n", Some("baby&PL")),
                entry("baby", "n", None),
                // `lying` derives from `lie` + `-ing` under MOR's `v-tie`
                // allomorphy: no verdict.
                entry("lying", "n", None),
                entry("lie", "v", None),
                // The affix entries the table must cover.
                affix("y", "adjsfx", "adj:n", true),
                affix("abil", "adjsfx", "adj:v", false),
                affix("pro", "pfx", "adj:n", true),
            ],
            source(),
        )
        .unwrap();
        assert_eq!(raw.communicator, vec!["whoops".to_string()]);
        // `whoop` is a communicator among a noun and a verb.
        assert_eq!(raw.communicator_among_others, vec!["whoop".to_string()]);
        assert_eq!(
            raw.noun,
            vec![
                NounVerdict {
                    form: "babies".into(),
                    lemma: "baby".into(),
                    number: NounNumber::Plural
                },
                NounVerdict {
                    form: "baby".into(),
                    lemma: "baby".into(),
                    number: NounNumber::Singular
                },
                NounVerdict {
                    form: "children".into(),
                    lemma: "child".into(),
                    number: NounNumber::Plural
                },
                NounVerdict {
                    form: "dog".into(),
                    lemma: "dog".into(),
                    number: NounNumber::Singular
                },
            ]
        );
    }

    #[test]
    fn derive_verdicts_fails_closed_on_an_uncovered_non_noun_suffix() {
        let err = derive_verdicts(
            vec![
                entry("dog", "n", None),
                affix("oid", "adjsfx", "adj:n", true),
            ],
            source(),
        )
        .unwrap_err();
        assert_eq!(
            err,
            UncoveredDerivation {
                suffix: "oid".into(),
                result: MorClass::Adjective,
                base: MorClass::Noun,
            }
        );
        // A POS-maintaining adjective suffix carries no `dcat` and is
        // checked by its own class.
        let err = derive_verdicts(
            vec![
                entry("big", "adj", None),
                mor_entry("most", "adjsfx", None, true, None),
            ],
            source(),
        )
        .unwrap_err();
        assert_eq!(err.suffix, "most");
        assert_eq!(
            (err.result, err.base),
            (MorClass::Adjective, MorClass::Adjective)
        );
        // A noun-producing suffix, a prefix, or a non-bare allomorph is not
        // the table's job.
        for harmless in [
            affix("ness", "ndsfx", "n:adj", true),
            affix("pro", "pfx", "adj:n", true),
            affix("oid", "adjsfx", "adj:n", false),
        ] {
            assert!(derive_verdicts(vec![entry("dog", "n", None), harmless], source()).is_ok());
        }
    }

    #[test]
    fn verdicts_constructor_rejects_bad_tokens_and_duplicates() {
        let base = || RawVerdicts {
            source: source(),
            communicator: vec!["whoops".into()],
            communicator_among_others: vec![],
            noun: vec![NounVerdict {
                form: "doggy".into(),
                lemma: "doggy".into(),
                number: NounNumber::Singular,
            }],
        };
        assert!(LexiconVerdicts::try_from(base()).is_ok());

        let mut upper = base();
        upper.communicator = vec!["Whoops".into()];
        assert_eq!(
            LexiconVerdicts::try_from(upper).unwrap_err(),
            LexiconVerdictsError::MalformedForm("Whoops".into())
        );

        let mut spaced = base();
        spaced.noun[0].lemma = "dog gy".into();
        assert_eq!(
            LexiconVerdicts::try_from(spaced).unwrap_err(),
            LexiconVerdictsError::MalformedLemma("dog gy".into())
        );

        let mut across = base();
        across.noun[0].form = "whoops".into();
        assert_eq!(
            LexiconVerdicts::try_from(across).unwrap_err(),
            LexiconVerdictsError::Duplicate("whoops".into())
        );

        let mut within = base();
        within.noun.push(within.noun[0].clone());
        assert_eq!(
            LexiconVerdicts::try_from(within).unwrap_err(),
            LexiconVerdictsError::Duplicate("doggy".into())
        );
    }

    #[test]
    fn verdict_lookup_is_case_insensitive_and_silent_on_unknowns() {
        let verdicts = LexiconVerdicts::try_from(RawVerdicts {
            source: source(),
            communicator: vec!["whoops".into()],
            communicator_among_others: vec![],
            noun: vec![NounVerdict {
                form: "doggy".into(),
                lemma: "doggy".into(),
                number: NounNumber::Singular,
            }],
        })
        .unwrap();
        assert_eq!(
            verdicts.verdict("Whoops"),
            Some(&LexiconVerdict::Communicator)
        );
        assert_eq!(
            verdicts.verdict("whoops"),
            Some(&LexiconVerdict::Communicator)
        );
        assert!(matches!(
            verdicts.verdict("doggy"),
            Some(LexiconVerdict::Noun(_))
        ));
        assert_eq!(verdicts.verdict("well"), None);
        assert_eq!(verdicts.communicator_count(), 1);
        assert_eq!(verdicts.noun_count(), 1);
    }

    /// The shipped data must load, and must carry the facts the rule exists
    /// for. `whoop` is deliberately absent: it is a communicator, a noun and
    /// a verb in the lexicon, so no verdict may be derived for it.
    #[test]
    fn embedded_english_verdicts_load() {
        let verdicts = embedded_english();
        assert!(
            verdicts.communicator_count() > 100,
            "communicator set is implausibly small"
        );
        assert!(
            verdicts.noun_count() > 1000,
            "noun set is implausibly small"
        );
        assert_eq!(
            verdicts.verdict("whoops"),
            Some(&LexiconVerdict::Communicator)
        );
        assert_eq!(
            verdicts.verdict("banana"),
            Some(&LexiconVerdict::Noun(NounVerdict {
                form: "banana".into(),
                lemma: "banana".into(),
                number: NounNumber::Singular,
            }))
        );
        // `doggy` is a noun-only ENTRY, but MOR can also derive it as an
        // adjective (`dog` + `-y`), so no verdict: the lexicon alone cannot
        // settle it. Likewise `sticky` (`stick`), `building` (`build`).
        assert_eq!(verdicts.verdict("doggy"), None);
        assert_eq!(verdicts.verdict("sticky"), None);
        assert_eq!(verdicts.verdict("building"), None);
        // Ambiguous communicators are recorded as such, never as a category.
        assert_eq!(
            verdicts.verdict("okay"),
            Some(&LexiconVerdict::CommunicatorAmongOthers)
        );
        assert_eq!(
            verdicts.verdict("whoop"),
            Some(&LexiconVerdict::CommunicatorAmongOthers)
        );
        assert_eq!(
            verdicts.verdict("well"),
            Some(&LexiconVerdict::CommunicatorAmongOthers)
        );
    }
