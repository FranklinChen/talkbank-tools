    /// Shortfalls are reported whatever the document's standing: an admitted
    /// document with a shortfall is never reported clean, and a diagnosed one
    /// reports its findings and its shortfalls together.
    #[test]
    fn shortfalls_are_reported_whatever_the_standing() {
        let refused = Shortfall::StageNotApplied {
            stage: OptionalStage::UtteranceSegmentation,
            refusal: crate::api::StageRefusalRecord::judged(
                JudgementBar::Construction,
                &[crate::api::FileOutputDiagnostics::coded_finding(
                    "E999",
                    "synthetic",
                )],
            ),
        };
        let admitted = PostValidated::produced(parse(VALID), ReleasedCommand::Transcribe);
        let OutputReport::Diagnosed(report) =
            OutputReport::of(&admitted, std::slice::from_ref(&refused))
        else {
            panic!("a shortfall is never reported clean");
        };
        assert!(
            report.findings().next().is_none(),
            "the document itself passed"
        );
        assert_eq!(report.shortfalls(), std::slice::from_ref(&refused));
        assert!(
            refused
                .to_string()
                .starts_with("utterance segmentation not applied")
        );

        let diagnosed =
            PostValidated::produced(generated_with_invalid_word(), ReleasedCommand::Transcribe);
        let shortfalls = [
            Shortfall::StageSkipped {
                stage: OptionalStage::UtteranceSegmentation,
            },
            Shortfall::StageSkipped {
                stage: OptionalStage::Morphosyntax,
            },
        ];
        let OutputReport::Diagnosed(report) = OutputReport::of(&diagnosed, &shortfalls) else {
            panic!("findings are reported");
        };
        assert!(report.findings().next().is_some());
        assert_eq!(report.shortfalls().len(), 2);
    }

    /// A requested merge still runs on a diagnosed output, and the merged
