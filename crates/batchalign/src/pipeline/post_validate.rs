//! Output admission: writers accept a proof, never unchecked CHAT bytes.
//!
//! Every production output retains Chatter's complete admission, including
//! tier alignment. Transformed documents use checked typed construction;
//! unchanged documents carry the original bytes bound to their admitted parse.
//! Neither route reparses generated CHAT or fabricates parser provenance.
//!
//! Applied analysis also satisfies command-specific completion checks.
//! Comparison adds a census-based preservation check, not an exemption from
//! CHAT validity. Declined analysis may remove declared decision tiers, but
//! the resulting document must still pass complete construction admission.
//!
//! Model edits consume the previous proof and establish a new one before
//! serialization. Failed optional abbreviation merging retains the unmerged
//! admitted output. Unchanged output skips merging and provenance injection.
//! Serialization is cached only after admission, from the admitted model.
//!
//! A separately named, test-only double can stand in for an admitted worker
//! result; it cannot construct Chatter's production admission payload.
//!
//! # Output our own producer generated
//!
//! Every route above refuses: a command that transforms CHAT someone
//! submitted fails the file rather than write a document Chatter does not
//! admit. Transcription is different in kind. Its CHAT is generated by our own
//! code from an ASR response, so an admission failure there is a fact about
//! the generated document (an ASR token such as `b2` or `Www` kept verbatim
//! for human review, or a defect in our builder), never bad user input, and
//! the generated document is the most valuable evidence anyone has of it.
//! [`PostValidated::produced`] is the one transition for that case. It runs
//! exactly the same judgement as [`PostValidated::gate_owned`] and never
//! fails: it returns a [`ProducedOutput`], which is either an admitted
//! [`PostValidated`] or a [`DiagnosedOutput`] carrying the model and the
//! complete, non-empty list of what the judgement found. Validation is not
//! relaxed; what changes is that the verdict travels beside the bytes instead
//! of replacing them.
//!
//! A [`PostValidated`] therefore proves admission, always: the diagnosed case
//! is a different type, so no stage that requires an admitted document can be
//! handed one, and no method needs an arm for it.
//!
//! ```mermaid
//! stateDiagram-v2
//!     [*] --> Judged: produced(model, command)
//!     Judged --> Admitted: judgement passes (PostValidated)
//!     Judged --> Diagnosed: judgement finds anything (DiagnosedOutput)
//!     Admitted --> Admitted: later stage (utseg, morphosyntax)
//!     Admitted --> Admitted: later stage refused, pre-stage kept, shortfall recorded
//!     Diagnosed --> Diagnosed: later stage skipped, shortfall recorded
//!     Admitted --> Written: writer, file Done (or Diagnosed with shortfalls)
//!     Diagnosed --> Written: writer, file Diagnosed with findings
//! ```
//!
//! # Requested work the written output does not carry
//!
//! A [`Shortfall`] is requested work the written document does not include,
//! and why: a later stage skipped because the generated document was
//! diagnosed, or an optional stage whose own output could not be admitted, so
//! the admitted document from before it was kept. Shortfalls are facts about
//! the run, not about the document, so they are carried beside the proof by
//! the producer that knows them and reported by the writer whatever the
//! document's standing ([`OutputReport::of`]). A file with any shortfall is
//! never reported clean.

